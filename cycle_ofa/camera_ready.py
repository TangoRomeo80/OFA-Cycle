"""Generate offline baselines and fixed-capacity variance diagnostics."""

from __future__ import annotations

from dataclasses import asdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
from tempfile import TemporaryDirectory
from typing import Callable

from . import __version__
from .diagnostics import diagnose_variance
from .experiments import BASE_SEED, PAPER_SIMULATION_GRID, _write_csv, derive_seed
from .offline import compare_offline

PAPER_VARIANCE_GRID = ((20, 5), (50, 5), (100, 5), (200, 5))
QUICK_GRID = ((8, 2), (12, 2))


def render_reviewer_tables(offline_rows: list[dict], variance_rows: list[dict]) -> str:
    """Render measured offline means and the same-path variance decomposition."""
    runs = offline_rows[0]["runs"]
    m = variance_rows[0]["m"]
    lines = [
        "% Generated by cycle-ofa camera-ready; regenerate instead of editing.",
        r"\begin{table}[t]", r"\centering",
        rf"\caption{{Paired greedy and offline-optimal total costs over {runs:,} runs. "
        r"Entries are mean $\pm$ 95\% CI half-width. The last column is the ratio "
        r"of sample means, with a paired delta-method interval; it is not the mean of per-run ratios.}",
        r"\label{tab:offline}", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{crrr}", r"\toprule",
        r"$(n,m)$ & greedy & offline optimum & ratio of means \\", r"\midrule",
    ]
    for row in offline_rows:
        greedy = f"{row['greedy_mean']:.3f}" + r"$\pm$" + f"{row['greedy_ci95_half_width']:.3f}"
        offline = f"{row['offline_mean']:.3f}" + r"$\pm$" + f"{row['offline_ci95_half_width']:.3f}"
        ratio = row["ratio_of_means"]
        ratio_ci = row["ratio_ci95_half_width"]
        comparison = (f"{ratio:.3f}" + r"$\pm$" + f"{ratio_ci:.3f}"
                      if ratio is not None and ratio_ci is not None else r"---")
        lines.append(f"({row['n']},{row['m']}) & {greedy} & {offline} & {comparison}" + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    lines += [
        r"\begin{table}[t]", r"\centering",
        rf"\caption{{Variance decomposition at fixed capacity $m={m}$ over {runs:,} "
        r"conditional trajectories. The removed positional contribution is $\bar S$ "
        r"with a 95\% CI half-width. The last column estimates "
        r"$1+\E[S]/\operatorname{Var}(Y)$; no asymptotic limit is asserted.}",
        r"\label{tab:variance}", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{rrrr}", r"\toprule",
        r"$n$ & $s_Y^2$ & removed positional variance & implied ratio \\", r"\midrule",
    ]
    for row in variance_rows:
        history = f"{row['conditional_variance']:,.2f}"
        noise = f"{row['mean_removed_variance']:,.2f}" + r"$\pm$" + f"{row['removed_variance_ci95_half_width']:.2f}"
        ratio = row["variance_ratio"]
        ratio_text = f"{ratio:.3f}" if ratio is not None else r"---"
        lines.append(f"{row['n']} & {history} & {noise} & {ratio_text}" + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def _camera_ready_in_directory(
    output: Path, *, profile: str, runs: int, seed: int,
    progress: Callable[[str], None] | None,
) -> dict:
    report = progress or (lambda message: None)
    offline_grid = PAPER_SIMULATION_GRID if profile == "paper" else QUICK_GRID
    variance_grid = PAPER_VARIANCE_GRID if profile == "paper" else QUICK_GRID
    offline_rows: list[dict] = []
    variance_rows: list[dict] = []
    for n, m in offline_grid:
        row_seed = derive_seed(seed, n, m, "offline-comparison")
        report(f"offline comparison n={n}, m={m}, runs={runs}, seed={row_seed}")
        offline_rows.append(asdict(compare_offline(n, m, runs=runs, seed=row_seed)))
    for n, m in variance_grid:
        row_seed = derive_seed(seed, n, m, "variance-diagnostic")
        report(f"variance diagnostic n={n}, m={m}, runs={runs}, seed={row_seed}")
        variance_rows.append(asdict(diagnose_variance(n, m, runs=runs, seed=row_seed)))
    _write_csv(output / "offline.csv", offline_rows)
    _write_csv(output / "variance.csv", variance_rows)
    (output / "reviewer_tables.tex").write_text(
        render_reviewer_tables(offline_rows, variance_rows), encoding="utf-8", newline="\n",
    )
    output_names = ("offline.csv", "variance.csv", "reviewer_tables.tex")
    manifest = dict(
        schema_version=1, package_version=__version__,
        generated_at_utc=datetime.now(timezone.utc).isoformat(),
        python_version=platform.python_version(), platform=platform.platform(),
        profile=profile, runs_per_case=runs, base_seed=seed,
        seed_derivation="First 8 SHA-256 bytes (big endian) of ASCII cycle-ofa-v1:{base_seed}:{n}:{m}:{method}",
        offline_grid=offline_grid, variance_grid=variance_grid,
        offline_seeds=[dict(n=r["n"], m=r["m"], seed=r["seed"]) for r in offline_rows],
        variance_seeds=[dict(n=r["n"], m=r["m"], seed=r["seed"]) for r in variance_rows],
        confidence_interval="mean +/- 1.96 * sqrt(unbiased_sample_variance / runs)",
        offline_ratio=(
            "Ratio of paired sample means greedy_mean/offline_mean, with a paired "
            "delta-method normal CI using their sample covariance; not a competitive-ratio bound."
        ),
        variance_decomposition="Var(C) = Var(Y) + E[S], S = sum_t Var(C_t | full facility sequence)",
        positional_variance="(a^3+b^3)/(12*(a+b)) - ((a^2+b^2)/(4*(a+b)))^2; singleton n^2/48",
        variance_ratio=(
            "1 + mean_removed_variance/conditional_variance, a same-path point estimate; "
            "null if the conditional sample variance vanishes. No ratio CI or limit claim."
        ),
        output_sha256={name: hashlib.sha256((output / name).read_bytes()).hexdigest()
                       for name in output_names},
    )
    (output / "manifest.json").write_text(
        json.dumps(manifest, indent=2, allow_nan=False) + "\n", encoding="utf-8", newline="\n",
    )
    return manifest


def camera_ready(
    output: str | Path, *, profile: str = "paper", runs: int | None = None,
    seed: int = BASE_SEED, progress: Callable[[str], None] | None = None,
) -> dict:
    """Stage all reviewer experiments before replacing published outputs.

    The paper profile uses the five original simulation cases for the offline
    baseline, and n=20,50,100,200 at fixed m=5 for variance diagnostics. The
    quick profile uses n=8,12 at m=2 and defaults to 100 runs. Neither profile
    changes the manuscript automatically.
    """
    if profile not in ("quick", "paper"):
        raise ValueError("profile must be 'quick' or 'paper'")
    if runs is None:
        runs = 100 if profile == "quick" else 10_000
    if isinstance(runs, bool) or not isinstance(runs, int) or runs < 2:
        raise ValueError("runs must be an integer >= 2")
    derive_seed(seed, 3, 1, "offline-comparison")
    derive_seed(seed, 3, 1, "variance-diagnostic")
    destination = Path(output)
    destination.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix=".cycle-ofa-camera-ready-", dir=destination) as temporary:
        staged = Path(temporary)
        manifest = _camera_ready_in_directory(
            staged, profile=profile, runs=runs, seed=seed, progress=progress,
        )
        (destination / "manifest.json").unlink(missing_ok=True)
        for name in ("offline.csv", "variance.csv", "reviewer_tables.tex", "manifest.json"):
            (staged / name).replace(destination / name)
    return manifest
