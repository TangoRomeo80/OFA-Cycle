"""Reproduce the paper grids and export machine-readable and LaTeX results."""

from __future__ import annotations

import csv
from dataclasses import asdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
from tempfile import TemporaryDirectory
from typing import Callable

from . import __version__
from .exact import ExactSolver
from .simulation import simulate
from .symmetry import bracelet_count

BASE_SEED = 20260822
PAPER_EXACT_GRID = tuple(
    (n, m) for m, largest in ((1, 12), (2, 12), (3, 9), (4, 8))
    for n in range(3, largest + 1)
)
PAPER_SIMULATION_GRID = ((8, 2), (8, 4), (20, 5), (50, 5), (200, 10))
PAPER_STATE_GRID = ((8, 2), (10, 2), (12, 2), (8, 3), (9, 3), (8, 4))
QUICK_EXACT_GRID = tuple((n, m) for m in (1, 2) for n in range(3, 7)) + ((8, 2),)
QUICK_SIMULATION_GRID = ((6, 1), (8, 2))


def derive_seed(base_seed: int, n: int, m: int, method: str) -> int:
    """Stable, distinct per-method seeds; independent of Python's hash salt."""
    if isinstance(base_seed, bool) or not isinstance(base_seed, int):
        raise ValueError("base_seed must be an integer")
    if method not in ("direct", "conditional"):
        raise ValueError("method must be 'direct' or 'conditional'")
    message = f"cycle-ofa-v1:{base_seed}:{n}:{m}:{method}".encode("ascii")
    return int.from_bytes(hashlib.sha256(message).digest()[:8], "big")


def _write_csv(path: Path, rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def render_tables(exact_rows: list[dict], simulation_rows: list[dict], profile: str) -> str:
    """Format computed values only; no hard-coded manuscript measurements."""
    values = {(row["n"], row["m"]): row for row in exact_rows}
    capacities = sorted({row["m"] for row in exact_rows})
    # The manuscript's cost table has n<=8 and complete rows across capacities.
    sizes = [n for n in range(3, 9) if all((n, m) in values for m in capacities)]
    lines = [
        "% Generated by cycle-ofa; regenerate instead of editing.",
        "% Monte Carlo rows use the documented cycle-ofa-v1 seed derivation.",
        r"\begin{table}[t]", r"\centering",
        r"\caption{Exact expected cost per arrival, $G_{n,m}/(mn)$.}",
        r"\label{tab:costs}", r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{c@{\quad}" + "r" * len(capacities) + "}",
        r"\toprule",
        "$n$ & " + " & ".join(f"$m={m}$" for m in capacities) + r" \\",
        r"\midrule",
    ]
    for n in sizes:
        cells = [f"{values[n, m]['per_arrival']:.4f}" for m in capacities]
        lines.append(f"{n} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    state_grid = PAPER_STATE_GRID if profile == "paper" else ((6, 2), (8, 2))
    lines += [
        r"\begin{table}[t]", r"\centering",
        r"\caption{Dihedral reduction. The stored-state count equals the bracelet count $B(n,m+1)$.}",
        r"\label{tab:states}", r"\setlength{\tabcolsep}{4.5pt}",
        r"\begin{tabular}{rrrrr}", r"\toprule",
        r"$n$ & $m$ & raw $(m+1)^n$ & stored & reduction \\", r"\midrule",
    ]
    for n, m in state_grid:
        row = values[n, m]
        raw, stored = row["raw_states"], row["stored_states"]
        lines.append(f"{n} & {m} & {raw:,} & {stored:,} & {raw / stored:.1f}" + r"$\times$ \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    indexed = {(r["n"], r["m"], r["method"]): r for r in simulation_rows}
    runs = simulation_rows[0]["runs"]
    lines += [
        r"\begin{table}[t]", r"\centering",
        rf"\caption{{Direct and conditional estimators over {runs:,} runs. "
        r"Entries are mean $\pm$ 95\% CI half-width; the last column is $s_D^2/s_C^2$.}",
        r"\label{tab:simulation}", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{crrr}", r"\toprule",
        r"$(n,m)$ & direct & conditional & variance ratio \\", r"\midrule",
    ]
    for n, m in dict.fromkeys((r["n"], r["m"]) for r in simulation_rows):
        direct, conditional = indexed[n, m, "direct"], indexed[n, m, "conditional"]
        cells = [f"{r['mean']:.3f}" + r"$\pm$" + f"{r['ci95_half_width']:.3f}"
                 for r in (direct, conditional)]
        denominator = conditional["sample_variance"]
        ratio = (f"{direct['sample_variance'] / denominator:.2f}" + r"$\times$"
                 if denominator > 0 else r"---")
        lines.append(f"({n},{m}) & " + " & ".join(cells) + " & " + ratio + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def _reproduce_in_directory(
    output: str | Path,
    *,
    profile: str = "quick",
    runs: int | None = None,
    seed: int = BASE_SEED,
    max_states: int | None = 1_000_000,
    progress: Callable[[str], None] | None = None,
) -> dict:
    """Run every experiment in a profile and write a provenance manifest last."""
    if profile not in ("quick", "paper"):
        raise ValueError("profile must be 'quick' or 'paper'")
    if runs is None:
        runs = 10_000 if profile == "paper" else 1_000
    if isinstance(runs, bool) or not isinstance(runs, int) or runs < 2:
        raise ValueError("runs must be an integer >= 2")
    derive_seed(seed, 3, 1, "direct")  # Validate before creating output files.
    exact_grid = PAPER_EXACT_GRID if profile == "paper" else QUICK_EXACT_GRID
    simulation_grid = PAPER_SIMULATION_GRID if profile == "paper" else QUICK_SIMULATION_GRID
    destination = Path(output)
    destination.mkdir(parents=True, exist_ok=True)
    report = progress or (lambda message: None)
    exact_rows: list[dict] = []
    simulation_rows: list[dict] = []
    for n, m in exact_grid:
        report(f"exact n={n}, m={m}")
        solver = ExactSolver(n, max_states=max_states)
        result = solver.solve(m)
        expected_states = bracelet_count(n, m + 1)
        if solver.state_count != expected_states:
            raise RuntimeError(f"state-count mismatch at ({n},{m})")
        exact_rows.append(dict(
            n=n, m=m, numerator=result.numerator, denominator=result.denominator,
            total_cost=float(result), per_arrival=float(result / (n * m)),
            raw_states=(m + 1) ** n, stored_states=solver.state_count,
            bracelet_count=expected_states,
        ))
    _write_csv(destination / "exact.csv", exact_rows)
    for n, m in simulation_grid:
        for method in ("direct", "conditional"):
            row_seed = derive_seed(seed, n, m, method)
            report(f"{method} n={n}, m={m}, runs={runs}, seed={row_seed}")
            stats = simulate(n, m, runs=runs, seed=row_seed, method=method)
            row = dict(n=n, m=m, method=method)
            row.update(asdict(stats))
            simulation_rows.append(row)
    _write_csv(destination / "simulation.csv", simulation_rows)
    (destination / "paper_tables.tex").write_text(
        render_tables(exact_rows, simulation_rows, profile), encoding="utf-8", newline="\n",
    )
    output_names = ("exact.csv", "simulation.csv", "paper_tables.tex")
    manifest = dict(
        schema_version=1, package_version=__version__,
        generated_at_utc=datetime.now(timezone.utc).isoformat(),
        python_version=platform.python_version(), platform=platform.platform(),
        profile=profile, runs_per_method=runs, base_seed=seed,
        seed_derivation="First 8 SHA-256 bytes (big endian) of ASCII cycle-ofa-v1:{base_seed}:{n}:{m}:{method}",
        confidence_interval="mean +/- 1.96 * sqrt(unbiased_sample_variance / runs)",
        exact_grid=exact_grid, simulation_grid=simulation_grid,
        max_states=max_states,
        manuscript_simulation_note=(
            "The original source and per-row seed derivation were not supplied. "
            "These are newly generated reproducible Monte Carlo results, not a "
            "bit-for-bit reconstruction of the original manuscript's simulations."
        ),
        output_sha256={name: hashlib.sha256((destination / name).read_bytes()).hexdigest()
                       for name in output_names},
    )
    (destination / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n",
    )
    return manifest


def reproduce(
    output: str | Path,
    *,
    profile: str = "quick",
    runs: int | None = None,
    seed: int = BASE_SEED,
    max_states: int | None = 1_000_000,
    progress: Callable[[str], None] | None = None,
) -> dict:
    """Stage a complete run before replacing any previously published results.

    A failed computation preserves existing output. During publication the old
    manifest is removed before replacing data; the new manifest is installed
    last, so an interrupted publication cannot leave a stale success marker.
    """
    if profile not in ("quick", "paper"):
        raise ValueError("profile must be 'quick' or 'paper'")
    if runs is not None and (isinstance(runs, bool) or not isinstance(runs, int) or runs < 2):
        raise ValueError("runs must be an integer >= 2")
    derive_seed(seed, 3, 1, "direct")
    ExactSolver(3, max_states=max_states)  # Validate the budget before writing.
    final_destination = Path(output)
    final_destination.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix=".cycle-ofa-run-", dir=final_destination) as temporary:
        staged = Path(temporary)
        manifest = _reproduce_in_directory(
            staged, profile=profile, runs=runs, seed=seed,
            max_states=max_states, progress=progress,
        )
        (final_destination / "manifest.json").unlink(missing_ok=True)
        for name in ("exact.csv", "simulation.csv", "paper_tables.tex", "manifest.json"):
            (staged / name).replace(final_destination / name)
    return manifest
